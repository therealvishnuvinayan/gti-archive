import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (path) => readFileSync(path, "utf8");
const resolver = read("src/lib/permissions/resolver.ts");
const profiles = read("src/lib/permissions/profiles.ts");
const users = read("src/components/users/users-workspace.tsx");
const overview = read("src/components/archives/archive-overview.tsx");
const categories = read("src/components/settings/project-master-data-workspace.tsx");
const page = read("src/app/(dashboard)/archives/settings/categories/page.tsx");
assert.ok(resolver.includes('if (permissionKey.startsWith("archive.")) return Boolean(user.id);'));
assert.ok(profiles.includes('archiveAccessGranted: true'));
assert.ok(profiles.includes('archiveAccessLevel: "FULL"'));
assert.ok(users.includes("Enabled for everyone"));
assert.ok(!users.includes("ArchiveAssetAccessPicker"));
assert.ok(!categories.includes("Restricted to selected people"));
assert.ok(overview.includes("/archives/settings/categories"));
assert.ok(page.includes("await requireUser()"));
assert.ok(page.includes("canManageItems") && page.includes("canDeleteItems"));
console.log("Archive full-access UI checks passed.");
